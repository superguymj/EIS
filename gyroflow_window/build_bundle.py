"""Mechanically assemble a single-file distribution from the tested modules."""
from __future__ import annotations

import argparse
import ast
import hashlib
import shutil
from pathlib import Path


CLI = '''
def main():
    import argparse
    import json
    from pathlib import Path
    parser = argparse.ArgumentParser(description="Finite-lookahead quaternion stabilization; wxyz, camera-to-world")
    parser.add_argument("input", help=".npy (N,4), or .npz with raw/orientations key")
    parser.add_argument("--output", required=True)
    parser.add_argument("--fps", type=float, default=30.0)
    parser.add_argument("--history", type=int, default=60)
    parser.add_argument("--emit", type=int, default=6)
    parser.add_argument("--future", type=int, default=15)
    parser.add_argument("--minimum-fov", type=float, default=0.8)
    parser.add_argument("--diagonal-fov", type=float, default=100.0)
    args = parser.parse_args()
    loaded = np.load(args.input, allow_pickle=False)
    if isinstance(loaded, np.lib.npyio.NpzFile):
        with loaded:
            raw = loaded["raw" if "raw" in loaded else "orientations"].copy()
    else:
        raw = loaded
    config = SmoothingConfig(fps=args.fps, minimum_fov=args.minimum_fov)
    window = WindowConfig(history=args.history, emit=args.emit, future=args.future)
    result = stabilize_window(raw, config, window, PinholeCamera(args.diagonal_fov))
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(output, orientations=result.orientations, fov=result.fov,
                        geometric_fov=result.geometric_fov)
    print(json.dumps({"output": str(output), "frames": len(result.orientations),
                      "minimum_fov": float(np.min(result.fov)) if len(result.fov) else None}, indent=2))


if __name__ == "__main__":
    main()
'''


def build(output):
    root = Path(__file__).parent
    names = ['math3d.py', 'geometry.py', 'gyroflow_global.py', 'sliding_window.py']
    pieces = ['# SPDX-License-Identifier: GPL-3.0-or-later\n'
              '# Generated by gyroflow_window.build_bundle; edit source modules, not this bundle.\n'
              '# Gyroflow reference: 2331ebb3c253fc7cf357642518b0c8bf2937f815.\n'
              '"""Standalone finite-lookahead quaternion stabilization; see docs/gyroflow-sliding-window.md."""\n'
              'from __future__ import annotations\n']
    for name in names:
        source = (root/name).read_text(encoding='utf-8')
        lines = source.splitlines(keepends=True)
        remove = set()
        for node in ast.parse(source).body:
            if isinstance(node, ast.ImportFrom) and (node.level or node.module == '__future__'):
                remove.update(range(node.lineno-1, node.end_lineno))
        digest = hashlib.sha256(source.encode()).hexdigest()
        pieces.append(f'\n# Source: {name}; SHA256: {digest}\n')
        pieces.append(''.join(line for i, line in enumerate(lines) if i not in remove))
    pieces.append(CLI)
    target = Path(output)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('\n'.join(pieces), encoding='utf-8')
    for notice in ['LICENSE', 'NOTICE.md']:
        shutil.copy2(root/notice, target.parent/notice)
    print(target)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', default='dist/gyroflow_sliding_window.py')
    build(parser.parse_args().output)
